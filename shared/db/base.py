"""SQLAlchemy declarative Base with a deterministic naming convention.

A fixed naming convention ensures Alembic autogenerate produces stable,
reproducible migrations across environments — which is a prerequisite for
the platform's "deterministic on identical inputs" principle.
"""

from __future__ import annotations

from sqlalchemy import MetaData
from sqlalchemy.orm import DeclarativeBase

NAMING_CONVENTION: dict[str, str] = {
    "ix": "ix_%(table_name)s_%(column_0_N_name)s",
    "uq": "uq_%(table_name)s_%(column_0_N_name)s",
    "ck": "ck_%(table_name)s_%(constraint_name)s",
    "fk": "fk_%(table_name)s_%(column_0_name)s_%(referred_table_name)s",
    "pk": "pk_%(table_name)s",
}

metadata = MetaData(naming_convention=NAMING_CONVENTION)


class Base(DeclarativeBase):
    """Project-wide ORM base. All models inherit from this class."""

    metadata = metadata
